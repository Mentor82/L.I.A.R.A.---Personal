# Shared by run_sandboxed.sh and run_sandboxed_shell.sh - sourced as a bash
# function library, never itself sudo-invoked/whitelisted directly. Node's
# equivalent of _ensure_session_venv.sh's shared-runner-venv trick: the
# sandbox has no live network access (run_sandboxed_shell.sh's own
# unshare --net comment explains why), so `npm install` inside it can never
# reach the real npm registry - a package like Konva has to already be
# sitting on disk, built once *outside* the sandbox (where real internet
# access exists - see /opt/liara/runner-node's own setup, done once via
# `npm install` in that directory as the deploy user, not from this script).
#
# A single ordinary symlink (not Python's env-var/.pth trick) is enough here:
# Node's own module resolution already walks up from cwd looking for a
# node_modules directory, and every bundler (Vite, webpack, esbuild) relies
# on that exact same walk - a symlinked node_modules "just works" for both
# `require()`/`import` and a bundled dev server, with no NODE_PATH env var
# whose bundler support is inconsistent.

ensure_session_node_modules() {
  local workspace_dir="$1"
  local shared_node_modules="/opt/liara/runner-node/node_modules"
  local target="$workspace_dir/node_modules"

  # Only symlink when nothing is there yet - never touches a real
  # node_modules directory the user (or a past, since-removed npm install
  # attempt) already created, same "don't clobber what's already there"
  # rule ensure_session_venv follows for an existing venv.
  if [ -e "$target" ] || [ -L "$target" ]; then
    return 0
  fi
  if [ ! -d "$shared_node_modules" ]; then
    return 0
  fi
  ln -sf "$shared_node_modules" "$target" 2>/dev/null || true
}
